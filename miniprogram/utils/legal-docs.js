function cloneDocument(doc) {
  return {
    key: String(doc.key || ""),
    title: String(doc.title || ""),
    shortTitle: String(doc.shortTitle || doc.title || ""),
    versionLine: String(doc.versionLine || ""),
    sections: (Array.isArray(doc.sections) ? doc.sections : []).map((section) => ({
      title: String((section && section.title) || ""),
      paragraphs: (Array.isArray(section && section.paragraphs) ? section.paragraphs : []).map((line) =>
        String(line || "")
      ),
    })),
    footer: (Array.isArray(doc.footer) ? doc.footer : []).map((line) => String(line || "")),
  };
}

function applyRuntimeSectionOverrides(doc) {
  const key = String((doc && doc.key) || "").trim();
  const overrides = RUNTIME_SECTION_PARAGRAPHS[key];
  if (!overrides || typeof overrides !== "object") {
    return cloneDocument(doc);
  }

  const nextDoc = cloneDocument(doc);
  nextDoc.sections = nextDoc.sections.map((section) => {
    const sectionTitle = String((section && section.title) || "");
    const paragraphs = overrides[sectionTitle];
    if (!Array.isArray(paragraphs)) {
      return section;
    }
    return {
      title: sectionTitle,
      paragraphs: paragraphs.map((line) => String(line || "")),
    };
  });
  return nextDoc;
}

function buildLegalDocument(doc, options) {
  if (!doc) return null;
  void options;
  return applyRuntimeSectionOverrides(doc);
}

function getLegalDocuments(options) {
  return DOCUMENTS.map((doc) => buildLegalDocument(doc, options));
}

function getLegalDocumentByKey(key, options) {
  const normalized = String(key || "").trim();
  const matched = DOCUMENTS.find((doc) => String(doc.key || "") === normalized) || DOCUMENTS[0];
  return matched ? buildLegalDocument(matched, options) : null;
}

